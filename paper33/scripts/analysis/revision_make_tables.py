#!/usr/bin/env python3
"""Paper 33 -- revision 2026-11-08: write the LaTeX tables of the revision appendix from the revision_* CSVs.

Reads (read-only): results/analysis/revision_sigma_pair_verdicts.csv, revision_heterogeneity.csv,
  revision_kl_budget_effects.csv, revision_kl_budget_sigma.csv, revision_outcome_classes.csv.
Writes (overwritten): paper/tables/t10_sigma_level.tex (tab:sigma-level), t11_heterogeneity.tex (tab:heterogeneity),
  t12_kl_budgets.tex (tab:kl-budgets), t13_outcome_classes.tex (tab:outcome-classes).

Run (from the paper root):
    scripts/figures/.venv/bin/python scripts/analysis/revision_make_tables.py
"""
from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / "results" / "analysis"
TAB = ROOT / "paper" / "tables"
PD = {"qwen": "Qwen", "gemma": "Gemma", "olmo": "OLMo", "mistral": "Mistral Small", "qwen-small": "Small pair"}
STAMP = f"% Auto-generated by scripts/analysis/revision_make_tables.py at {datetime.now(timezone.utc):%Y-%m-%dT%H:%MZ} -- do not edit by hand.\n"


def f(x, d=1):
    s = f"{x:+.{d}f}"
    return s.replace("-", "$-$")


def ci(lo, hi, d=1):
    return f"[{f(lo, d)}, {f(hi, d)}]"


def sigma_table():
    v = pd.read_csv(RES / "revision_sigma_pair_verdicts.csv")
    est = {"direction raw": "Direction, raw", "direction adjusted": "Direction, adjusted", "ARA raw": "ARA, raw",
           "ARA adjusted": "ARA, adjusted", "H2 contrast (ARA - direction)": "H2 contrast"}
    L = [STAMP, "% src: results/analysis/revision_sigma_pair_verdicts.csv (scripts/analysis/revision_seed_variance.py)\n",
         "\\begin{table*}[t]\n\\centering\\scriptsize\n\\setlength{\\tabcolsep}{3pt}\n",
         "\\caption{Per-pair class effects (pp) under two models of run-to-run variance. Constant: $\\sigma=9.15$~pp per "
         "cell [6.40, 16.07] (the intervals of Table~\\ref{tab:pair-effects}). Refusal-level: $\\sigma_L=0.83$ [0.58, 1.45] "
         "per cell on the logit scale, mapped to pp at each cell's rate $p$ as $\\sigma_L\\,p(1-p)$. Intervals add prompt "
         "sampling and the run-to-run variance at the point estimate of $\\sigma$; the last two columns mark (\\checkmark) "
         "whether the interval excludes zero at the lower limit, point estimate and upper limit of $\\sigma$ "
         "(lo\\,/\\,pt\\,/\\,hi).}\n\\label{tab:sigma-level}\n",
         "\\begin{tabular}{@{}lllllcc@{}}\n\\toprule\n",
         "Pair & Estimand & Effect & Constant $\\sigma$ & Refusal-level $\\sigma$ & Excl.\\ 0, const. & Excl.\\ 0, level \\\\\n",
         " & & & [95\\% interval] & [95\\% interval] & lo/pt/hi & lo/pt/hi \\\\\n\\midrule\n"]
    for pair in PD:
        g = v[v.pair == pair]
        for i, r in enumerate(g.itertuples()):
            mk = lambda tag: "/".join("\\checkmark" if getattr(r, f"excl0_{tag}_{k}") else "--" for k in ("lo", "point", "hi"))
            L.append(f"{PD[pair] if i == 0 else ''} & {est[r.estimand]} & {f(r.estimate_pp)} & "
                     f"{ci(r.lo_const_point, r.hi_const_point)} & {ci(r.lo_level_point, r.hi_level_point)} & "
                     f"{mk('const')} & {mk('level')} \\\\\n")
        if pair != "qwen-small":
            L.append("\\addlinespace\n")
    L.append("\\bottomrule\n\\end{tabular}\n\\end{table*}\n")
    (TAB / "t10_sigma_level.tex").write_text("".join(L))


def het_table():
    h = pd.read_csv(RES / "revision_heterogeneity.csv")
    est = {"direction raw": "Direction, raw", "direction adjusted": "Direction, adjusted", "ARA raw": "ARA, raw",
           "ARA adjusted": "ARA, adjusted", "H2 contrast (ARA - direction)": "H2 contrast"}
    cols = [("pp", "prompt sampling only", "Prompt only"),
            ("pp", "prompt + seed, constant sigma_pp (point)", "+ seed, const."),
            ("pp", "prompt + seed, logit-level sigma (point)", "+ seed, level"),
            ("log-odds", "prompt sampling only", "Prompt only"),
            ("log-odds", "prompt + seed, constant sigma_L (point)", "+ seed")]
    L = [STAMP, "% src: results/analysis/revision_heterogeneity.csv (scripts/analysis/revision_seed_variance.py)\n",
         "\\begin{table}[t]\n\\centering\\scriptsize\n\\setlength{\\tabcolsep}{2.5pt}\n",
         "\\caption{Between-pair heterogeneity of the four main-pair effects (Cochran's $Q$ with 3~df, $p$ value and $I^2$) "
         "with three kinds of within-pair variance: prompt sampling only, prompt sampling plus constant run-to-run "
         "variance, and (pp scale only) prompt sampling plus refusal-level run-to-run variance, each at the point estimate "
         "of $\\sigma$. Across the 95\\% interval of $\\sigma$, $I^2$ of the raw direction-based pp effect is 90\\% (lower "
         "limit) to 39\\% (upper limit) with constant and 73\\% to 0\\% with refusal-level variance.}\n"
         "\\label{tab:heterogeneity}\n\\begin{tabular}{@{}lccccc@{}}\n\\toprule\n",
         " & \\multicolumn{3}{c}{pp scale} & \\multicolumn{2}{c}{log-odds scale} \\\\\n",
         "\\cmidrule(lr){2-4}\\cmidrule(l){5-6}\n",
         "Estimand & " + " & ".join(c[2] for c in cols) + " \\\\\n\\midrule\n"]
    for e, name in est.items():
        cells = []
        for sc, var, _ in cols:
            r = h[(h.estimand == e) & (h.scale == sc) & (h.variance == var)].iloc[0]
            p = "$<$0.001" if r.Q_p < 0.001 else f"{r.Q_p:.3f}"
            cells.append(f"{r.Q:.1f}; {p}; {100*r.I2:.0f}\\%")
        L.append(f"{name} & " + " & ".join(cells) + " \\\\\n")
    L.append("\\bottomrule\n\\end{tabular}\n\\end{table}\n")
    (TAB / "t11_heterogeneity.tex").write_text("".join(L))


def kl_table():
    e = pd.read_csv(RES / "revision_kl_budget_effects.csv")
    s = pd.read_csv(RES / "revision_kl_budget_sigma.csv").set_index("quantity").sigma_dev
    q = ["t0.05", "t0.1", "t0.2", "t0.5", "t1", "auc"]
    qh = ["$\\le$0.05", "$\\le$0.1", "$\\le$0.2", "$\\le$0.5", "$\\le$1.0", "Area"]
    est = {"direction class": "Direction", "ara": "ARA", "H2 contrast": "H2 contrast"}
    L = [STAMP, "% src: results/analysis/revision_kl_budget_effects.csv, revision_kl_budget_sigma.csv "
         "(scripts/analysis/revision_kl_budgets.py; input paper/figures/data/trials.csv)\n",
         "\\begin{table*}[t]\n\\centering\\scriptsize\n\\setlength{\\tabcolsep}{3.5pt}\n",
         "\\caption{Generation effects on the development set at several first-token KL budgets (newer minus older model; "
         "dev keyword refusals of 100 of the best completed trial at KL $\\le t$, including the original at KL = 0) and on "
         "the area under the refusal--KL front (mean front value over 200 log-spaced budgets from 0.01 to 1). Direction: "
         "mean of the direction-based methods; H2: ARA minus direction. $^{*}$Beyond 1.96 run-to-run standard errors, "
         "from the ten small-pair seed pairs on the same quantity (run-to-run SD per cell: "
         + ", ".join(f"{h} {s[k]:.1f}" for k, h in zip(q, qh)) +
         "; prompt sampling of the 100 dev prompts is not included). The KL $\\le$ 0.1 column belongs to the selected models; "
         "only those were evaluated on held-out prompts (last column, WildGuard, pp). Dev counts are optimised and therefore "
         "optimistic.}\n\\label{tab:kl-budgets}\n\\begin{tabular}{@{}llrrrrrrr@{}}\n\\toprule\n",
         "Pair & Estimand & " + " & ".join(qh) + " & Held-out \\\\\n\\midrule\n"]
    for pair in PD:
        for i, (k, name) in enumerate(est.items()):
            g = e[(e.pair == pair) & (e.estimand == k)].set_index("quantity")
            cells = [f"{f(g.loc[x, 'effect'])}{'$^{*}$' if g.loc[x, 'beyond_noise'] else ''}" for x in q]
            L.append(f"{PD[pair] if i == 0 else ''} & {name} & " + " & ".join(cells) +
                     f" & {f(g.iloc[0].heldout_effect_pp)} \\\\\n")
        if pair != "qwen-small":
            L.append("\\addlinespace\n")
    L.append("\\bottomrule\n\\end{tabular}\n\\end{table*}\n")
    (TAB / "t12_kl_budgets.tex").write_text("".join(L))


def outcome_table():
    o = pd.read_csv(RES / "revision_outcome_classes.csv")
    md = {"original": "Original", "dim": "DiM", "mpoa": "MPOA", "som": "SOM", "jspace": "J-space", "ara": "ARA"}
    L = [STAMP, "% src: results/analysis/revision_outcome_classes.csv (scripts/analysis/revision_outcome_classes.py; "
         "input cell_rates.csv, harmful_all)\n",
         "\\begin{table*}[t]\n\\centering\\scriptsize\n\\setlength{\\tabcolsep}{3.5pt}\n",
         "\\caption{Outcome classes on the 972 harmful held-out prompts (\\% of responses), older and newer model of each "
         "pair: refusal (WildGuard, non-degenerate responses), complete compliance, incomplete compliance (generation "
         "stopped at the 512-token limit) and degenerate responses (Methods). Rows may not add to 100 because of rounding "
         "and a few unscored responses.}\n\\label{tab:outcome-classes}\n",
         "\\begin{tabular}{@{}llrrrrrrrr@{}}\n\\toprule\n",
         " & & \\multicolumn{4}{c}{Older model} & \\multicolumn{4}{c}{Newer model} \\\\\n",
         "\\cmidrule(lr){3-6}\\cmidrule(l){7-10}\n",
         "Pair & Condition & Ref. & Compl. & Incompl. & Degen. & Ref. & Compl. & Incompl. & Degen. \\\\\n\\midrule\n"]
    for pair in PD:
        g = o[o.pair == pair]
        meths = [m for m in md if m in set(g.method)]
        for i, m in enumerate(meths):
            cells = []
            for gen in (0, 1):
                r = g[(g.method == m) & (g.generation.str.contains("new") == bool(gen))].iloc[0]
                cells += [f"{100*r.refusal:.1f}", f"{100*r.complete_compliance:.1f}",
                          f"{100*r.incomplete_compliance:.1f}", f"{100*r.degenerate:.1f}"]
            L.append(f"{PD[pair] if i == 0 else ''} & {md[m]} & " + " & ".join(cells) + " \\\\\n")
        if pair != "qwen-small":
            L.append("\\addlinespace\n")
    L.append("\\bottomrule\n\\end{tabular}\n\\end{table*}\n")
    (TAB / "t13_outcome_classes.tex").write_text("".join(L))


if __name__ == "__main__":
    sigma_table()
    het_table()
    kl_table()
    outcome_table()
    print("wrote paper/tables/t10_sigma_level.tex, t11_heterogeneity.tex, t12_kl_budgets.tex, t13_outcome_classes.tex")
