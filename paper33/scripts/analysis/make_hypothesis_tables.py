def table_h3():
    gap = {(r["group"], r["variant"]): r for r in rows("h3_gap_pooled.csv") if r["subset"] == "harmful_all"}
    kap = {r["group"]: r for r in rows("h3_agreement_pairs.csv")
           if r["subset"] == "harmful" and r["group_type"] == "pooled" and r["rater1"] == "kw"
           and r["rater2"] == "wg"}
    groups = [
        ("original", "kw_vs_wg", "Originals"),
        ("ablated_primary", "kw_vs_wg", "Ablated (seed 1), all"),
        ("ablated_primary:main", "kw_vs_wg", r"\quad main study"),
        ("ablated_primary:small", "kw_vs_wg", r"\quad small pair"),
        ("ablated_primary", "kw_vs_wg_complete_only", r"\quad responses ending before the cap"),
        ("ablated_primary", "kw_vs_wg_capped_only", r"\quad responses truncated at 512 tokens"),
        ("role:control", "kw_vs_wg", r"$\gamma$-MPOA control"),
        ("role:external", "kw_vs_wg", "Community releases"),
        ("role:replicate", "kw_vs_wg", "Seed-2 replicates (small pair)"),
        ("all_judged", "kw_vs_wg", "All judged models"),
    ]
    out = [header("results/analysis/h3_gap_pooled.csv (subset harmful_all), h3_agreement_pairs.csv "
                  "(subset harmful, pooled, kw vs wg)")]
    out.append(r"""\begin{table}[t]
\centering\footnotesize
\setlength{\tabcolsep}{3pt}
\caption{Keyword matching versus WildGuard on the same held-out responses to the 972 harmful prompts (H3).
Keyword: any of Heretic's 33 refusal markers in the full response (at most 512 tokens). Gap: keyword minus
WildGuard refusal rate, pp, with prompt-cluster bootstrap 95\% interval (H3 predicted a negative gap). kw/WG only: responses counted
as refusals by keyword matching only / by WildGuard only. $\kappa$: Cohen's kappa with prompt-bootstrap 95\%
interval. Ablated: the 42 seed-1 models selected from the primary runs.}
\label{tab:h3-gap}
\begin{tabular}{lrrrrlrl}
\toprule
Models & Cells & Responses & Kw, \% & WG, \% & Gap, pp [95\% CI] & kw/WG only & $\kappa$ [95\% CI] \\
\midrule""")
    for g, var, disp in groups:
        r = gap[(g, var)]
        k = kap.get(g) if var == "kw_vs_wg" else None
        k_s = f"{num(k['kappa'], 2)} {ci(k['kappa_lo'], k['kappa_hi'], 2)}" if k else "--"
        out.append(
            f"{disp} & {r['n_cells']} & {intfmt(r['n'])} & {num(r['rate1'], 1, 100)} & {num(r['rate2'], 1, 100)} & "
            f"{num(r['gap'], 1, 100, True)} {ci(r['gap_lo'], r['gap_hi'], 1, 100, True)} & "
            f"{intfmt(r['b_r1_only'])}/{intfmt(r['c_r2_only'])} & {k_s} \\\\")
        if g == "ablated_primary" and var == "kw_vs_wg_capped_only":
            out.append(r"\midrule")
        if g == "original":
            out.append(r"\midrule")
        if g == "role:replicate":
            out.append(r"\midrule")
    out.append(r"""\bottomrule
\end{tabular}
\end{table}
""")
    return "\n".join(out)


def main():
    os.makedirs(OUT, exist_ok=True)
    for name, fn in [("t4_h1_heldout.tex", table_h1), ("t5_h2_contrasts.tex", table_h2), ("t6_h3_gap.tex", table_h3)]:
        path = os.path.join(OUT, name)
        with open(path, "w") as f:
            f.write(fn())
        print("wrote", os.path.relpath(path, ROOT))


if __name__ == "__main__":
    main()
