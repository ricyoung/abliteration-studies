def table_h2():
    con = {r["pair"]: r for r in rows("h1h2_h2_contrasts.csv") if r["judge"] == "wg" and r["subset"] == "all"}
    tests = {r["test_id"]: r for r in rows("h1h2_tests.csv")
             if r["judge"] == "wg" and r["subset"] == "all" and r["family"] == "H2"}
    mod = {(r["model"], r["term"]): r for r in rows("h1h2_models.csv")
           if r["judge"] == "wg" and r["subset"] == "all" and r["scope"] == "main"}

    def verdict(est, p_holm):
        if Decimal(p_holm) >= Decimal("0.05"):
            return "n.s."
        return "predicted" if Decimal(est) < 0 else "opposite"

    out = [header("results/analysis/h1h2_h2_contrasts.csv, h1h2_tests.csv (family H2), h1h2_models.csv "
                  "(scope main; judge wg, subset all)")]
    out.append(r"""\begin{table*}[t]
\centering\footnotesize
\setlength{\tabcolsep}{3pt}
\caption{Generation $\times$ method-class interaction (H2) on held-out WildGuard refusal. ARA and direction
mean: generation effects (newer minus older model, pp) of ARA and of the mean of the direction-based methods
(DiM, MPOA, SOM; on the small pair also J-space). RD contrast: ARA minus direction mean, pp, item-bootstrap
95\% interval. GEE: generation $\times$ class interaction in log-odds (exchangeable, clustered by prompt) with
95\% interval; $p_\mathrm{Holm}$ over the six H2 tests. VB: the planned mixed logistic model (random
intercepts for prompt and, in the pooled fit, family), posterior mean $\pm$ 1.96 SD. Pooled (main): the
four main-study pairs. H2 predicts a negative
interaction (ARA loses less effectiveness on the newer model); sign vs.\ H2: GEE interaction significant after
Holm and negative (predicted) or positive (opposite), or not significant (n.s.). $^{c}$The RD contrast and the
log-odds interaction have opposite signs.}
\label{tab:h2-contrasts}
\begin{tabular}{lrrlllll}
\toprule
Pair & ARA, & Direction & RD contrast, pp & GEE, log-odds & $p_\mathrm{Holm}$ & VB, log-odds & Sign \\
 & pp & mean, pp & [95\% CI] & [95\% CI] & & [95\% CrI] & vs.\ H2 \\
\midrule""")
    for key, disp, old_m, new_m in PAIRS:
        c = con[key]
        t = tests[f"{key}: generation x class"]
        v = verdict(c["gee_interaction"], t["p_holm"])
        rd_neg = Decimal(c["rd_hi"]) < 0
        rd_pos = Decimal(c["rd_lo"]) > 0
        g = Decimal(c["gee_interaction"])
        if (rd_neg and g > 0) or (rd_pos and g < 0):
            v += "$^{c}$"
        out.append(
            f"{disp} & {num(c['delta_ara'], 1, 100, True)} & {num(c['delta_direction_mean'], 1, 100, True)} & "
            f"{num(c['rd_contrast'], 1, 100, True)} {ci(c['rd_lo'], c['rd_hi'], 1, 100, True)} & "
            f"{num(c['gee_interaction'], 2, 1, True)} {ci(c['gee_lo'], c['gee_hi'], 2, 1, True)} & "
            f"{pval(t['p_holm'])} & "
            f"{num(c['vb_interaction'], 2, 1, True)} {ci(c['vb_lo'], c['vb_hi'], 2, 1, True)} & {v} \\\\")
    t = tests["pooled main: generation x class"]
    vb = mod[("vb_planned", "gen_new:opt")]
    out.append(r"\midrule")
    out.append(
        f"Pooled (main) & -- & -- & -- & {num(t['estimate'], 2, 1, True)} {ci(t['lo'], t['hi'], 2, 1, True)} & "
        f"{pval(t['p_holm'])} & {num(vb['estimate'], 2, 1, True)} {ci(vb['lo'], vb['hi'], 2, 1, True)} & "
        f"{verdict(t['estimate'], t['p_holm'])} \\\\")
    out.append(r"""\bottomrule
\end{tabular}
\end{table*}
""")
    return "\n".join(out)


