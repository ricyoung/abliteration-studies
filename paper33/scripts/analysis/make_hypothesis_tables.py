#!/usr/bin/env python3
"""make_hypothesis_tables.py -- LaTeX tables of the held-out hypothesis tests (H1, H2, H3) for paper 33.

Stdlib only; reads (never writes) results/analysis/*.csv written by run_all.sh and writes ONLY
paper/tables/t4_h1_heldout.tex, t5_h2_contrasts.tex and t6_h3_gap.tex. Run after run_all.sh:
    python3 scripts/analysis/make_hypothesis_tables.py

Sources (judge = WildGuard `wg`, subset `all` / `harmful_all` unless stated):
  t4  h1h2_cells.csv (Wilson rates), h1h2_generation_effects.csv (Newcombe differences, exact McNemar b/c,
      baseline-adjusted effects), h1h2_tests.csv (family H1, Holm over 23 tests; subset excl_advbench for the
      robustness mark); seednoise_flags.csv / seednoise_sigma.csv (seed-noise column, added 2026-11-06; written by
      seednoise_flags.py, which must be run first).
  t5  h1h2_h2_contrasts.csv (per-pair RD contrast, GEE and VB interactions), h1h2_tests.csv (family H2, Holm
      over 6 tests), h1h2_models.csv (scope main: gee_planned / vb_planned gen_new:opt).
  t6  h3_gap_pooled.csv (variants kw_vs_wg, kw_vs_wg_complete_only, kw_vs_wg_capped_only),
      h3_agreement_pairs.csv (subset harmful, group_type pooled, kw vs wg Cohen's kappa).
Rounding: ROUND_HALF_UP on the CSV text (1 decimal for % and pp, 2 for log-odds and kappa, 3 for p).
"""
from __future__ import annotations

import csv
import datetime as _dt
import os
from decimal import Decimal, ROUND_HALF_UP

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
AN = os.path.join(ROOT, "results", "analysis")
OUT = os.path.join(ROOT, "paper", "tables")

PAIRS = [  # pair key, display, older, newer
    ("qwen", "Qwen", "Qwen2.5-32B", "Qwen3.8-27B"),
    ("gemma", "Gemma", "Gemma-2-27B", "Gemma-4-31B"),
    ("olmo", "OLMo", "OLMo-2-32B", "Olmo-3.1-32B"),
    ("mistral", "Mistral Small", "Mistral-Small-2409", "Mistral-Small-3.2"),
    ("qwen-small", "Small pair", "Qwen2.5-7B", "Qwen3.5-4B"),
]
METHODS = ["original", "dim", "mpoa", "som", "jspace", "ara"]
METHOD_TEX = {"original": "Original", "dim": "DiM", "mpoa": "MPOA", "som": "SOM", "jspace": "J-space",
              "ara": "ARA"}
STAMP = _dt.datetime.now(_dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def rows(name):
    with open(os.path.join(AN, name), newline="") as f:
        return list(csv.DictReader(f))


def q(x, nd):
    return Decimal(x).quantize(Decimal(1).scaleb(-nd), rounding=ROUND_HALF_UP)


def num(x, nd=1, scale=1, sign=False):
    """Format a CSV number (string) for LaTeX; scale=100 for proportions -> %/pp."""
    v = q(Decimal(x) * scale, nd)
    if v == 0:
        v = abs(v)
    s = f"{v:.{nd}f}"
    if s.startswith("-"):
        return "$-$" + s[1:]
    return ("+" + s) if sign else s


def ci(lo, hi, nd=1, scale=1, sign=False):
    return f"[{num(lo, nd, scale, sign)}, {num(hi, nd, scale, sign)}]"


def pval(p):
    p = Decimal(p)
    if p < Decimal("0.001"):
        return "$<$0.001"
    return f"{q(p, 3):.3f}"


def intfmt(x):
    return f"{int(x):,}".replace(",", "{,}")


def header(src):
    return (f"% Auto-generated by scripts/analysis/make_hypothesis_tables.py at {STAMP} -- do not edit by hand.\n"
            f"% src: {src}\n")


# ---------------------------------------------------------------------------------------------------------
def table_h1():
    cells = {(r["label"]): r for r in rows("h1h2_cells.csv") if r["judge"] == "wg" and r["subset"] == "all"}
    eff = {(r["pair"], r["method"]): r for r in rows("h1h2_generation_effects.csv")
           if r["judge"] == "wg" and r["subset"] == "all"}
    tests = rows("h1h2_tests.csv")
    holm_all = {(r["pair"], r["method"]): r for r in tests
                if r["judge"] == "wg" and r["subset"] == "all" and r["family"] == "H1" and r["method"]}
    holm_ex = {(r["pair"], r["method"]): r for r in tests
               if r["judge"] == "wg" and r["subset"] == "excl_advbench" and r["family"] == "H1" and r["method"]}
    failed = {lab for lab, r in cells.items() if r["method"] != "original" and r["orig_rate"]
              and Decimal(r["diff_vs_orig"]) >= 0}
    # seed-noise column (added 2026-11-06): written by scripts/analysis/seednoise_flags.py, which must run first
    for need in ("seednoise_flags.csv", "seednoise_sigma.csv"):
        if not os.path.exists(os.path.join(AN, need)):
            raise SystemExit(f"missing results/analysis/{need}: run scripts/analysis/seednoise_flags.py first")
    noise = {(r["pair"], r["method"]): r["seed_noise_flag"] for r in rows("seednoise_flags.csv")
             if r["scope"] == "main"}
    sig = {r["quantity"]: r for r in rows("seednoise_sigma.csv")}
    s_sig = sig["sigma (per-cell run-to-run SD), pp"]
    s_sdd = sig["SD_diff (older-minus-newer difference), pp"]
    s_thr = sig["threshold = 2 * SD_diff, pp"]
    n_exc = sum(v == "exceeds seed noise" for v in noise.values())
    noise_note = (
        rf"$^{{s}}$Seed noise: ``exceeds'' if $|$new $-$ old$|$ is larger than {num(s_thr['estimate'], 1)}~pp, "
        rf"twice the SD ({num(s_sdd['estimate'], 1)}~pp) of an older-minus-newer difference between two "
        rf"independently optimised cells, otherwise ``within'' ({n_exc} of {len(noise)} exceed); the per-cell "
        rf"run-to-run SD, {num(s_sig['estimate'], 1)}~pp {ci(s_sig['lo'], s_sig['hi'], 1)}, is estimated from the "
        rf"seed-1 versus seed-2 held-out refusal of the ten small-pair cells (\S\ref{{sec:res-h1}}) and assumed to "
        rf"transfer to the main pairs. Not given for the small pair, whose replicate is the source of the estimate "
        rf"(Figure~\ref{{fig:seed-heldout}}).")

    out = [header("results/analysis/h1h2_cells.csv, h1h2_generation_effects.csv, h1h2_tests.csv "
                  "(judge wg; subsets all and excl_advbench); seednoise_flags.csv, seednoise_sigma.csv")]
    out.append(r"""\begin{table*}[t]
\centering\footnotesize
\setlength{\tabcolsep}{3.6pt}
\caption{Held-out residual refusal of the older and newer model of each pair (H1). Rates: share of the 972
harmful held-out prompts whose response WildGuard labels a refusal, with Wilson 95\% intervals. Difference:
newer minus older model in percentage points (pp) with Newcombe 95\% intervals; $b$/$c$: prompts refused only
by the older / only by the newer model (exact McNemar test); $p_\mathrm{Holm}$: Holm over the 23 tests of the
H1 family (21 pair $\times$ method tests and two pooled terms); $^{u}$for the originals the unadjusted McNemar $p$
is given, as they are the baseline rather than an H1 test. Baseline-adjusted: the method's generation effect minus
that of the originals, pp [95\% CI]. Each modified model is the dev-set selection of its cell (first-token KL
$\le 0.1$, seed~1). $^{a}$Not significant after Holm when the 44 prompts that overlap the search prompts are
excluded. $^{b}$Failed edit: held-out refusal at or above the model's own original.""")
    out.append(noise_note + "}")
    out.append(r"""\label{tab:h1-heldout}
\begin{tabular}{@{}llllrlll@{}}
\toprule
Condition & Older, \% & Newer, \% & New $-$ old, pp & $b$/$c$ & $p_\mathrm{Holm}$ & Baseline-adj., pp & Seed \\
 & [95\% CI] & [95\% CI] & [95\% CI] & & & [95\% CI] & noise$^{s}$ \\
\midrule""")
    first_pair = True
    for key, disp, old_m, new_m in PAIRS:
        if not first_pair:
            out.append(r"\midrule")
        first_pair = False
        out.append(rf"\multicolumn{{8}}{{l}}{{\emph{{{disp}: {old_m} $\to$ {new_m}}}}} \\")
        for m in METHODS:
            e = eff.get((key, m))
            if e is None:
                continue
            co, cn = cells[e["old_label"]], cells[e["new_label"]]
            old_s = f"{num(co['rate'], 1, 100)} {ci(co['lo'], co['hi'], 1, 100)}"
            new_s = f"{num(cn['rate'], 1, 100)} {ci(cn['lo'], cn['hi'], 1, 100)}"
            if e["new_label"] in failed:
                new_s += "$^{b}$"
            if e["old_label"] in failed:
                old_s += "$^{b}$"
            d_s = f"{num(e['delta'], 1, 100, True)} {ci(e['delta_lo'], e['delta_hi'], 1, 100, True)}"
            bc = f"{e['old_only_b']}/{e['new_only_c']}"
            if m == "original":
                p_s = pval(e["p_mcnemar"]) + "$^{u}$"
                did = "--"
            else:
                t = holm_all[(key, m)]
                p_s = pval(t["p_holm"])
                tx = holm_ex.get((key, m))
                if Decimal(t["p_holm"]) < Decimal("0.05") and tx is not None and \
                        Decimal(tx["p_holm"]) >= Decimal("0.05"):
                    p_s += "$^{a}$"
                did = f"{num(e['did_baseline_adj'], 1, 100, True)} {ci(e['did_lo'], e['did_hi'], 1, 100, True)}"
            fl = noise.get((key, m))
            sn = "--" if fl is None else ("exceeds" if fl == "exceeds seed noise" else "within")
            out.append(f"{METHOD_TEX[m]} & {old_s} & {new_s} & {d_s} & {bc} & {p_s} & {did} & {sn} \\\\")
    out.append(r"""\bottomrule
\end{tabular}
\end{table*}
""")
    return "\n".join(out)


