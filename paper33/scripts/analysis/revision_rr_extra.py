from scipy import stats

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "results" / "analysis"
TAB = ROOT / "paper" / "tables"
RUNS = ROOT / "runs" / "mc-h200-1" / "runs"
PAIRS = ["qwen", "gemma", "olmo", "mistral", "qwen-small"]
MAIN = ["qwen", "gemma", "olmo", "mistral"]
PAIR_NAME = {"qwen": "Qwen", "gemma": "Gemma", "olmo": "OLMo", "mistral": "Mistral Small", "qwen-small": "Small pair"}
DIR = ["dim", "mpoa", "som", "jspace"]
B = 2000
STAMP = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%MZ")


def fmt(x: float, d: int = 1) -> str:
    s = f"{x:+.{d}f}"
    return s.replace("-", "$-$")


# ============================================================================ (1) retention intervals
def retention_analysis(L: list[str]) -> pd.DataFrame:
    rj = pd.read_csv(OUT / "responses_judged.csv.gz", low_memory=False,
                     usecols=["label", "pair", "role", "method", "gen_new", "kind", "id", "ref_wg"])
    h = rj[(rj.kind == "harmful") & rj.role.isin(["original", "primary", "replicate"])].copy()
    h["y"] = h.ref_wg.map({True: 1.0, False: 0.0, "True": 1.0, "False": 0.0})
    W = h.pivot(index="id", columns="label", values="y")
    lab = {}
    for r in h.drop_duplicates("label").itertuples():
        seed = 2 if r.role == "replicate" else 1
        lab[(r.pair, r.method, int(r.gen_new), seed)] = r.label
    rng = np.random.default_rng(20261108)
    n = len(W)
    boots = rng.integers(0, n, size=(B, n))

    def ret(pair, method, g, seed=1, idx=None):
        o = W[lab[(pair, "original", g, 1)]].values
        e = W[lab[(pair, method, g, seed)]].values
        if idx is not None:
            o, e = o[idx], e[idx]
        m = (o == 1) & ~np.isnan(e)
        return float(np.nanmean(e[m]))

    # (b) run-to-run SD of retention from the ten small-pair seed pairs
    d = []
    for g in (0, 1):
        for meth in DIR + ["ara"]:
            if ("qwen-small", meth, g, 2) in lab:
                d.append(ret("qwen-small", meth, g, 2) - ret("qwen-small", meth, g, 1))
    d = np.array(d)
    assert len(d) == 10, len(d)
    sig = float(np.sqrt(np.mean(d ** 2) / 2))
    ss = float(np.sum(d ** 2))
    sig_lo = float(np.sqrt(ss / (2 * stats.chi2.ppf(0.975, len(d)))))
    sig_hi = float(np.sqrt(ss / (2 * stats.chi2.ppf(0.025, len(d)))))
    pd.DataFrame([dict(quantity="sigma_ret (retention, per cell)", n_seed_pairs=len(d), sigma_pp=100 * sig,
                       sigma_lo_pp=100 * sig_lo, sigma_hi_pp=100 * sig_hi,
                       d_pp="; ".join(f"{100 * x:+.1f}" for x in d))]).to_csv(OUT / "revision_rr_retention_sigma.csv",
                                                                               index=False)
    L.append(f"## (1) Conditional retention: run-to-run SD sigma_ret = {100 * sig:.2f} pp "
             f"[{100 * sig_lo:.2f}, {100 * sig_hi:.2f}] (10 small-pair seed pairs)")

    old = pd.read_csv(OUT / "revision_retention.csv").set_index(["pair", "estimand"])
    rows = []
    for pair in PAIRS:
        dms = [m for m in DIR if (pair, m, 0, 1) in lab]
        k = len(dms)
        est, bt = {}, {}
        for meth in dms + ["ara"]:
            est[meth] = ret(pair, meth, 1) - ret(pair, meth, 0)
            bt[meth] = np.array([ret(pair, meth, 1, 1, b) - ret(pair, meth, 0, 1, b) for b in boots])
        dmean, dbt = float(np.mean([est[m] for m in dms])), np.mean([bt[m] for m in dms], axis=0)
        items = [(m, est[m], bt[m], 2.0) for m in dms + ["ara"]]
        items += [("direction class", dmean, dbt, 2.0 / k), ("H2 contrast", est["ara"] - dmean, bt["ara"] - dbt,
                                                              2.0 + 2.0 / k)]
        for name, e, b, mult in items:
            ref = old.loc[(pair, name)]
            assert abs(100 * e - ref.effect_pp) < 1e-9, (pair, name)
            assert abs(100 * np.percentile(b, 2.5) - ref.lo) < 1e-9, (pair, name)
            se_b = float(np.std(b, ddof=1))
            se_s = float(np.sqrt(mult) * sig)
            se_t = float(np.hypot(se_b, se_s))
            rows.append(dict(pair=pair, estimand=name, n_direction_methods=k, effect_pp=100 * e,
                             lo_prompt=100 * np.percentile(b, 2.5), hi_prompt=100 * np.percentile(b, 97.5),
                             se_prompt_pp=100 * se_b, seed_var_multiplier=mult, se_seed_pp=100 * se_s,
                             se_total_pp=100 * se_t, lo_total=100 * (e - 1.96 * se_t), hi_total=100 * (e + 1.96 * se_t),
                             excludes_zero_total=bool(abs(e) > 1.96 * se_t),
                             lo_total_sigma_hi=100 * (e - 1.96 * np.hypot(se_b, np.sqrt(mult) * sig_hi)),
                             hi_total_sigma_hi=100 * (e + 1.96 * np.hypot(se_b, np.sqrt(mult) * sig_hi))))
    R = pd.DataFrame(rows)
    R.to_csv(OUT / "revision_rr_retention.csv", index=False)
    for r in R[R.estimand.isin(["direction class", "ara", "H2 contrast"])].itertuples():
        L.append(f"- {r.pair} {r.estimand}: {r.effect_pp:+.1f}; prompt [{r.lo_prompt:+.1f}, {r.hi_prompt:+.1f}]; "
                 f"prompt + seed [{r.lo_total:+.1f}, {r.hi_total:+.1f}]{' *' if r.excludes_zero_total else ''}")
    return R


# ============================================================================ (2) search wall-clock time
CELL_RUN = {  # cell -> completed seed-1 search process used for the released model
    "qwen3.8-27b__ara": "qwen3.8-27b__ara__core-s1-clean",
    "qwen2.5-32b__ara": "qwen2.5-32b__ara__core-s1-r2",
    "mistral-small-3.2__ara": "mistral-small-3.2__ara__core-s1-r2",
    "mistral-small-3.2__dim": "mistral-small-3.2__dim__core-s1-r2",
    "mistral-small-3.2__mpoa": "mistral-small-3.2__mpoa__core-s1-r2",
}
EXCLUDE = {"qwen3.8-27b__mpoa": "resumed after an out-of-memory failure; search split over three processes"}


def search_time(L: list[str]) -> pd.DataFrame:
    rows = []
    for model in ["qwen2.5-32b", "qwen3.8-27b", "gemma-2-27b", "gemma-4-31b", "olmo-2-32b", "olmo-3.1-32b",
                  "mistral-small-2409", "mistral-small-3.2"]:
        for meth in ["dim", "mpoa", "som", "ara"]:
            cell = f"{model}__{meth}"
            run = CELL_RUN.get(cell, f"{cell}__core-s1")
            if cell in EXCLUDE:
                run = f"{cell}__core-s1-resume1"
            meta = (RUNS / run / "meta.txt").read_text()
            ws = int(re.search(r"^wall_seconds: (\d+)", meta, re.M).group(1))
            ec = int(re.search(r"^exit_code: (-?\d+)", meta, re.M).group(1))
            assert ec == 0, run
            rows.append(dict(cell=cell, model=model, method=meth, method_class="ARA" if meth == "ara" else "direction",
                             run=run, wall_seconds=ws, wall_minutes=ws / 60, in_summary=cell not in EXCLUDE,
                             note=EXCLUDE.get(cell, "")))
    T = pd.DataFrame(rows)
    T.to_csv(OUT / "revision_rr_search_time.csv", index=False)
    S = T[T.in_summary]
    L.append("\n## (2) Wall-clock time per completed 100-trial main-study search (H200 box; meta.txt wall_seconds)")
    for cls, s in S.groupby("method_class"):
        L.append(f"- {cls}: n = {len(s)}, median {s.wall_minutes.median():.1f} min, range {s.wall_minutes.min():.1f}"
                 f"-{s.wall_minutes.max():.1f} min, total {s.wall_seconds.sum() / 3600:.1f} h")
    L.append(f"- all {len(S)} included searches: total {S.wall_seconds.sum() / 3600:.1f} h; excluded: "
             + "; ".join(f"{k} ({v})" for k, v in EXCLUDE.items()))
    return T


# ============================================================================ (3) heterogeneity tables
EST = [("direction raw", "Direction, raw"), ("direction adjusted", "Direction, adjusted"), ("ARA raw", "ARA, raw"),
       ("ARA adjusted", "ARA, adjusted"), ("H2 contrast (ARA - direction)", "H2 contrast")]
VAR_PP = [("prompt sampling only", "Prompt only"), ("prompt + seed, constant sigma_pp (point)", "+ seed, const."),
          ("prompt + seed, logit-level sigma (point)", "+ seed, level")]
VAR_LO = [("prompt sampling only", "Prompt only"), ("prompt + seed, constant sigma_L (point)", "+ seed")]


def pfmt(p: float) -> str:
    return "$<$0.001" if p < 0.001 else f"{p:.3f}"


def het_tables(L: list[str]) -> None:
    H = pd.read_csv(OUT / "revision_heterogeneity.csv").set_index(["estimand", "scale", "variance"])
    V = pd.read_csv(OUT / "revision_pair_variances.csv")
    lines = [f"% Auto-generated by scripts/analysis/revision_rr_extra.py at {STAMP} -- do not edit by hand.",
             "% src: results/analysis/revision_heterogeneity.csv (scripts/analysis/revision_seed_variance.py); tau^2 in pp^2",
             "% (pp scale, tau2 x 10^4) and log-odds^2. Same Q, p and I^2 as t11_heterogeneity.tex, with tau^2 added.",
             r"\begin{table}[t]", r"\centering\scriptsize", r"\setlength{\tabcolsep}{2pt}",
             r"\caption{Between-pair heterogeneity of the four main-pair effects with three kinds of within-pair "
             r"variance: prompt sampling only, prompt sampling plus constant run-to-run variance, and (pp scale only) "
             r"prompt sampling plus refusal-level run-to-run variance, each at the point estimate of $\sigma$. Each "
             r"cell gives Cochran's $Q$ (3~df); its $p$ value; $I^2$; and the DerSimonian--Laird between-pair variance "
             r"$\tau^2$ (pp$^2$ on the pp scale, squared log-odds on the log-odds scale). Across the 95\% interval of "
             r"$\sigma$, $I^2$ of the raw direction-based pp effect is 90\% (lower limit) to 39\% (upper limit) with "
             r"constant and 73\% to 0\% with refusal-level variance. The within-pair variances are in "
             r"Table~\ref{tab:pair-variances}.}",
             r"\label{tab:heterogeneity}", r"\begin{tabular}{@{}lccccc@{}}", r"\toprule",
             r" & \multicolumn{3}{c}{pp scale} & \multicolumn{2}{c}{log-odds scale} \\",
             r"\cmidrule(lr){2-4}\cmidrule(l){5-6}",
             "Estimand & " + " & ".join(n for _, n in VAR_PP) + " & " + " & ".join(n for _, n in VAR_LO) + r" \\",
             r"\midrule"]
    for est, name in EST:
        cells = []
        for scale, vs in (("pp", VAR_PP), ("log-odds", VAR_LO)):
            for v, _ in vs:
                r = H.loc[(est, scale, v)]
                t2 = r.tau2 * (1e4 if scale == "pp" else 1)
                t2s = f"{t2:.0f}" if scale == "pp" else f"{t2:.2f}"
                cells.append(f"{r.Q:.1f}; {pfmt(r.Q_p)}; {100 * r.I2:.0f}\\%; {t2s}")
        lines.append(f"{name} & " + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    (TAB / "t11b_heterogeneity_tau.tex").write_text("\n".join(lines) + "\n")
    r = H.loc[("direction raw", "pp", "prompt + seed, constant sigma_pp (point)")]
    L.append(f"\n## (3) tau^2: direction raw pp const. point {1e4 * r.tau2:.0f} pp^2 (tau {100 * r.tau:.1f} pp)")
    for est, _ in EST:
        for scale, v in (("pp", "prompt + seed, constant sigma_pp (point)"),
                         ("pp", "prompt + seed, logit-level sigma (point)"),
                         ("log-odds", "prompt + seed, constant sigma_L (point)")):
            rr = H.loc[(est, scale, v)]
            L.append(f"- {est} / {scale} / {v}: tau2 {rr.tau2 * (1e4 if scale == 'pp' else 1):.3g}, I2 {rr.I2:.3f}")

    # per-pair within-pair variances (point estimates of sigma)
    cols = [("pp", "prompt sampling only", 1e4), ("pp", "prompt + seed, constant sigma_pp (point)", 1e4),
            ("pp", "prompt + seed, logit-level sigma (point)", 1e4), ("log-odds", "prompt sampling only", 1),
            ("log-odds", "prompt + seed, constant sigma_L (point)", 1)]
    lines = [f"% Auto-generated by scripts/analysis/revision_rr_extra.py at {STAMP} -- do not edit by hand.",
             "% src: results/analysis/revision_pair_variances.csv (var_within; pp scale x 10^4 = pp^2)",
             r"\begin{table}[t]", r"\centering\scriptsize", r"\setlength{\tabcolsep}{3pt}",
             r"\caption{Within-pair variances of the four main-pair effects used as inverse-variance weights in "
             r"Table~\ref{tab:heterogeneity}, at the point estimate of $\sigma$: prompt sampling only, and prompt "
             r"sampling plus constant or refusal-level run-to-run variance. pp scale in pp$^2$; log-odds scale in "
             r"squared log-odds. The constant run-to-run term is the same for every pair (2$\sigma^2$ per method, "
             r"2$\sigma^2/3$ for the direction-class mean), so on that variance model the pairs are weighted almost "
             r"equally.}",
             r"\label{tab:pair-variances}", r"\begin{tabular}{@{}llrrrrr@{}}", r"\toprule",
             r" & & \multicolumn{3}{c}{pp scale (pp$^2$)} & \multicolumn{2}{c}{log-odds scale} \\",
             r"\cmidrule(lr){3-5}\cmidrule(l){6-7}",
             r"Estimand & Pair & Prompt only & + seed, const. & + seed, level & Prompt only & + seed \\", r"\midrule"]
    for i, (est, name) in enumerate(EST):
        for j, pair in enumerate(MAIN):
            vals = []
            for scale, v, f in cols:
                s = V[(V.pair == pair) & (V.estimand == est) & (V.scale == scale) & (V.variance == v)]
                assert len(s) == 1, (pair, est, scale, v)
                x = float(s.var_within.iloc[0]) * f
                vals.append(f"{x:.1f}" if scale == "pp" else f"{x:.3f}")
            lines.append(f"{name if j == 0 else ''} & {PAIR_NAME[pair]} & " + " & ".join(vals) + r" \\")
        if i < len(EST) - 1:
            lines.append(r"\addlinespace")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    (TAB / "t14_pair_variances.tex").write_text("\n".join(lines) + "\n")


# ============================================================================ (4) H2 table split, retention table
def h2_tables() -> None:
    src = (TAB / "t5_h2_contrasts.tex").read_text()
    rows = [ln for ln in src.splitlines() if re.match(r"^(Qwen|Gemma|OLMo|Mistral Small|Small pair|Pooled \(main\)) &",
                                                     ln)]
    assert len(rows) == 6, rows
    parsed = []
    for ln in rows:
        c = [x.strip() for x in ln.rstrip("\\ ").rstrip("\\").split("&")]
        assert len(c) == 8, c
        parsed.append(c)
    hdr = f"% Auto-generated by scripts/analysis/revision_rr_extra.py at {STAMP} -- do not edit by hand.\n" \
          "% src: paper/tables/t5_h2_contrasts.tex (make_hypothesis_tables.py; results/analysis/h1h2_h2_contrasts.csv,\n" \
          "% h1h2_tests.csv, h1h2_models.csv); columns split only, no number changed.\n"
    main = [hdr.rstrip("\n"), r"\begin{table*}[t]", r"\centering\footnotesize", r"\setlength{\tabcolsep}{3pt}",
            r"\caption{Generation $\times$ method-class interaction (H2) on held-out WildGuard refusal. ARA and direction",
            r"mean: generation effects (newer minus older model, pp) of ARA and of the mean of the direction-based methods",
            r"(DiM, MPOA, SOM; on the small pair also J-space). RD contrast: ARA minus direction mean, pp, item-bootstrap",
            r"95\% interval. GEE: generation $\times$ class interaction in log-odds (exchangeable, clustered by prompt) with",
            r"95\% interval; $p_\mathrm{Holm}$ over the six H2 tests. Pooled (main): the four main-study pairs. All",
            r"intervals here reflect prompt sampling only; the per-pair intervals with run-to-run variance are in",
            r"Table~\ref{tab:pair-effects}, and the planned mixed-model estimates in Table~\ref{tab:h2-vb}. H2 predicts a",
            r"negative interaction (ARA loses less effectiveness on the newer model); sign vs.\ H2: GEE interaction",
            r"significant after Holm and negative (predicted) or positive (opposite), or not significant (n.s.).",
            r"$^{c}$The RD contrast and the log-odds interaction have opposite signs.}",
            r"\label{tab:h2-contrasts}", r"\begin{tabular}{lrrllll}", r"\toprule",
            r"Pair & ARA, & Direction & RD contrast, pp & GEE, log-odds & $p_\mathrm{Holm}$ & Sign \\",
            r" & pp & mean, pp & [95\% CI] & [95\% CI] & & vs.\ H2 \\", r"\midrule"]
    for k, c in enumerate(parsed):
        if c[0].startswith("Pooled"):
            main.append(r"\midrule")
        main.append(" & ".join(c[:6] + [c[7]]) + r" \\")
    main += [r"\bottomrule", r"\end{tabular}", r"\end{table*}"]
    (TAB / "t5b_h2_contrasts_main.tex").write_text("\n".join(main) + "\n")
    vb = [hdr.rstrip("\n"), r"\begin{table}[!htbp]", r"\centering\footnotesize",
          r"\caption{Planned mixed logistic model of the H2 interaction (variational Bayes; random intercepts for prompt",
          r"and, in the pooled fit, pair): posterior mean of the generation $\times$ class interaction in log-odds",
          r"$\pm$ 1.96 posterior SD, next to the GEE estimate of Table~\ref{tab:h2-contrasts}. The model has no",
          r"pair-specific generation or interaction slopes, so it cannot represent between-pair heterogeneity",
          r"(\S\ref{sec:setup-stats}).}",
          r"\label{tab:h2-vb}", r"\begin{tabular}{lll}", r"\toprule",
          r"Pair & GEE, log-odds [95\% CI] & VB, log-odds [95\% CrI] \\", r"\midrule"]
    for c in parsed:
        if c[0].startswith("Pooled"):
            vb.append(r"\midrule")
        vb.append(f"{c[0]} & {c[4]} & {c[6]}" + r" \\")
    vb += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    (TAB / "t15_h2_vb.tex").write_text("\n".join(vb) + "\n")


def retention_table(R: pd.DataFrame, sig: pd.Series) -> None:
    lines = [f"% Auto-generated by scripts/analysis/revision_rr_extra.py at {STAMP} -- do not edit by hand.",
             "% src: results/analysis/revision_rr_retention.csv, revision_rr_retention_sigma.csv",
             r"\begin{table}[!htbp]", r"\centering\footnotesize", r"\setlength{\tabcolsep}{4pt}",
             r"\caption{Conditional refusal retention: generation effect (newer minus older model, pp) on the share of "
             r"the prompts refused by a model's own original that the edited model still refused (WildGuard, 972 "
             r"harmful held-out prompts). Prompt: prompt-cluster bootstrap 95\% interval (2,000 resamples). Prompt + "
             r"seed: adds a run-to-run standard deviation of retention of "
             f"{sig.sigma_pp:.1f}~pp [{sig.sigma_lo_pp:.1f}, {sig.sigma_hi_pp:.1f}] per cell, estimated from the ten "
             r"small-pair seed pairs, with the multipliers of Table~\ref{tab:pair-effects}. $^{*}$Prompt + seed "
             r"interval excludes zero.}",
             r"\label{tab:retention}", r"\begin{tabular}{llrll}", r"\toprule",
             r"Pair & Estimand & Effect & Prompt [95\% CI] & Prompt + seed [95\% CI] \\", r"\midrule"]
    names = {"direction class": "Direction", "ara": "ARA", "H2 contrast": "H2 contrast"}
    for i, pair in enumerate(PAIRS):
        s = R[R.pair == pair].set_index("estimand")
        for j, est in enumerate(["direction class", "ara", "H2 contrast"]):
            r = s.loc[est]
            star = "$^{*}$" if r.excludes_zero_total else ""
            lines.append(f"{PAIR_NAME[pair] if j == 0 else ''} & {names[est]} & {fmt(r.effect_pp)} & "
                         f"[{fmt(r.lo_prompt)}, {fmt(r.hi_prompt)}] & [{fmt(r.lo_total)}, {fmt(r.hi_total)}]{star}"
                         + r" \\")
        if i < len(PAIRS) - 1:
            lines.append(r"\addlinespace")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    (TAB / "t16_retention.tex").write_text("\n".join(lines) + "\n")


def main() -> None:
    L = ["# Re-review revision analyses (revision_rr_extra.py)\n"]
    R = retention_analysis(L)
    search_time(L)
    het_tables(L)
    h2_tables()
    retention_table(R, pd.read_csv(OUT / "revision_rr_retention_sigma.csv").iloc[0])
    (OUT / "revision_rr_summary.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
